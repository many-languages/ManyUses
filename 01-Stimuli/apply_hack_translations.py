def apply_translations(lang_folder, lang_dict):
    path = f"{BASE}/{lang_folder}/{lang_folder}_concreteness_candidates.csv"
    with open(path) as f:
        rows = list(csv.DictReader(f))
    fieldnames = list(rows[0].keys())
    if "gloss_source" not in fieldnames:
        fieldnames.append("gloss_source")
    n_filled = 0
    for r in rows:
        current = r.get("gloss_english")
        missing = current is None or current == "" or current == "NA"
        if missing and r["word"] in lang_dict:
            r["gloss_english"] = lang_dict[r["word"]]
            r["gloss_source"] = "hack_llm_translation"
            n_filled += 1
        else:
            r.setdefault("gloss_source", "")
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    print(f"{lang_folder}: filled {n_filled} glosses (dict had {len(lang_dict)} entries)")

apply_translations("German", GERMAN)
apply_translations("Dutch", DUTCH)
